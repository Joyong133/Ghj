function roomArea(r) { const [x0, z0, x1, z1] = r.rect; return Math.abs((x1 - x0) * (z1 - z0)); }
function roomAt(x, z) {
  // 작은 방부터 찾는다 (복도가 큰 방과 겹치지 않도록 정의되어 있지만 안전하게)
  let best = null, ba = Infinity;
  for (const r of ROOMS) { const [x0, z0, x1, z1] = r.rect; if (x >= x0 && x <= x1 && z >= z0 && z <= z1) { const a = roomArea(r); if (a < ba) { ba = a; best = r; } } }
  return best;
}
function roomById(id) { return ROOMS.find((r) => r.id === id); }
