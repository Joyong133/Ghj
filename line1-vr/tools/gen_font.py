#!/usr/bin/env python3
"""Builds the glyph atlas (assets/font.png) and its metrics (cpp/font_data.h).

The atlas holds printable ASCII plus every non-ASCII character that appears in
the C++ sources, so run this again after changing any on-screen text:

    python3 tools/gen_font.py /usr/share/fonts/truetype/nanum/NanumSquareB.ttf
"""
import glob
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CPP = os.path.join(ROOT, "app/src/main/cpp")
SIZE = 64      # pixels per em
PAD = 4
ATLAS_W = 1024

font_path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/nanum/NanumSquareB.ttf"
font = ImageFont.truetype(font_path, SIZE)

chars = set(chr(c) for c in range(32, 127))
for path in glob.glob(os.path.join(CPP, "*.cpp")) + glob.glob(os.path.join(CPP, "*.h")):
    if os.path.basename(path) in ("font_data.h", "stb_image.h"):
        continue
    with open(path, encoding="utf-8") as f:
        chars.update(c for c in f.read() if ord(c) > 127)
chars = sorted(chars)

glyphs = []  # (cp, bbox, advance)
x, y, row_h = PAD, PAD, 0
placements = []
# Code point 1 is a solid block, used to draw rectangles with the text shader.
placements.append((1, x, y, 8, 8, None))
x += 8 + PAD
row_h = 8
for ch in chars:
    bbox = font.getbbox(ch, anchor="ls")  # relative to the baseline
    adv = font.getlength(ch)
    w, h = bbox[2] - bbox[0], bbox[3] - bbox[1]
    if w <= 0 or h <= 0:
        placements.append((ord(ch), 0, 0, 0, 0, (bbox, adv)))
        continue
    if x + w + PAD > ATLAS_W:
        x, y, row_h = PAD, y + row_h + PAD, 0
    placements.append((ord(ch), x, y, w, h, (bbox, adv)))
    x += w + PAD
    row_h = max(row_h, h)
height = 1
while height < y + row_h + PAD:
    height *= 2

img = Image.new("L", (ATLAS_W, height), 0)
draw = ImageDraw.Draw(img)
lines = []
for cp, px, py, w, h, info in placements:
    if info is None:
        draw.rectangle([px, py, px + w - 1, py + h - 1], fill=255)
        lines.append((cp, (px + 2) / ATLAS_W, (py + 2) / height, (px + w - 2) / ATLAS_W, (py + h - 2) / height,
                      0, 0, 1, 1, 1))
        continue
    bbox, adv = info
    if w > 0:
        draw.text((px - bbox[0], py - bbox[1]), chr(cp), font=font, fill=255, anchor="ls")
    # Half a texel of margin keeps neighbouring glyphs out of the filter footprint.
    m = 1
    lines.append((cp, (px - m) / ATLAS_W, (py - m) / height, (px + w + m) / ATLAS_W, (py + h + m) / height,
                  (bbox[0] - m) / SIZE, -(bbox[3] + m) / SIZE, (bbox[2] + m) / SIZE, -(bbox[1] - m) / SIZE,
                  adv / SIZE) if w > 0 else (cp, 0, 0, 0, 0, 0, 0, 0, 0, adv / SIZE))
lines.sort()

os.makedirs(os.path.join(ROOT, "app/src/main/assets"), exist_ok=True)
img.save(os.path.join(ROOT, "app/src/main/assets/font.png"), optimize=True)
with open(os.path.join(CPP, "font_data.h"), "w") as f:
    f.write("// Generated by tools/gen_font.py - do not edit.\n#pragma once\n#include <cstdint>\n\n")
    f.write("struct Glyph {\n    uint32_t cp;\n    float u0, v0, u1, v1;  // atlas rectangle (v0 = top)\n"
            "    float x0, y0, x1, y1;  // quad in em, relative to the baseline, y up\n    float adv;\n};\n\n")
    f.write("static const Glyph kGlyphs[] = {\n")
    for l in lines:
        f.write("    {%d, %.5ff, %.5ff, %.5ff, %.5ff, %.4ff, %.4ff, %.4ff, %.4ff, %.4ff},\n" % l)
    f.write("};\nstatic const int kGlyphCount = %d;\n" % len(lines))
print("glyphs:", len(lines), "atlas:", ATLAS_W, "x", height)
